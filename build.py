def material_css(build: Build) -> str:
    tokens = build.tokens
    blocks = [
        tokens_css(build),
        "/* The theme's own properties, resolved from the tokens, for both colour schemes. */",
        "",
    ]
    schemes: tuple[tuple[str, ThemeId], ...] = (("default", "light"), ("slate", "dark"))
    for scheme, theme in schemes:
        lines = [f'[data-md-color-scheme="{scheme}"] {{']
        for prop, name in MATERIAL_ROLES:
            ref = (
                f"var(--idfkit-color-primitive-{name.removeprefix('color.primitive.')})"
                if name.startswith("color.primitive.")
                else _primitive_var(tokens, name, theme)
            )
            lines.append(f"  {prop}: {ref};")
        lines += [
            "  --md-text-font: var(--idfkit-font-stack-text);",
            "  --md-code-font: var(--idfkit-font-stack-code);",
            "}",
            "",
        ]
        blocks.append("\n".join(lines))
    return "\n".join(blocks)


