def envelop_primitives_css(build: Build) -> str:
    tokens = build.tokens
    lines = [
        f"/* {build.header} Tier-one brand primitives in the application's form; the roles alias these. */",
        "",
        ":root {",
    ]
    for token in tokens.colors("role"):
        name = token.name.removeprefix("color.role.").replace(".", "-")
        value = tokens.resolve(token.name, "light")
        lines.append(f"  --p-brand-{name}: {hex_to_oklch(value)}; /* {value} */")
    for token in tokens.colors("primitive"):
        value = tokens.resolve(token.name, "light")
        lines.append(f"  --p-brand-{token.name.removeprefix('color.primitive.')}: {hex_to_oklch(value)}; /* {value} */")
    lines += ["}", "", "[data-theme='dark'] {"]
    for token in tokens.colors("role"):
        name = token.name.removeprefix("color.role.").replace(".", "-")
        value = tokens.resolve(token.name, "dark")
        lines.append(f"  --p-brand-{name}: {hex_to_oklch(value)}; /* {value} */")
    lines += ["}", ""]
    return "\n".join(lines)


