def schema_coverage_md(build: Build, schema: Mapping[str, object]) -> str:
    styles = stytch_styles(build, "dark")
    lines = [
        f"# Style coverage of the sign-in widget ({build.tag})",
        "",
        f"Schema: `{schema['package']}` {schema['version']}, `{schema['type']}`, read on {schema['readOn']}.",
        "",
        "## Set",
        "",
        "| Property | Value (dark theme) |",
        "| -------- | ------------------ |",
    ]

    def walk(node: Mapping[str, object], value: object, prefix: str) -> None:
        for key, kind in node.items():
            path = f"{prefix}.{key}" if prefix else key
            if isinstance(kind, Mapping):
                walk(kind, value[key] if isinstance(value, Mapping) else {}, path)
            else:
                set_value = value[key] if isinstance(value, Mapping) and key in value else None
                lines.append(f"| `{path}` | `{set_value}` |" if set_value is not None else f"| `{path}` | not set |")

    properties = schema["properties"]
    if not isinstance(properties, Mapping):
        raise BuildError("providers/stytch-styles.json: properties must be an object")
    walk(properties, styles, "")
    lines += [
        "",
        "## Not expressible",
        "",
        "Parts of the standard the schema has no property for. Each is an Exception under `auth` in `touchpoints.toml` (FR-026).",
        "",
        "| Part | Why |",
        "| ---- | --- |",
    ]
    lines += [f"| `{part}` | {why} |" for part, why in STYTCH_NOT_EXPRESSIBLE]
    lines.append("")
    return "\n".join(lines)


