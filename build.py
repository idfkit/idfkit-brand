def rsvg_convert(svg: Path, png: Path, width: int, height: int | None = None) -> None:
    if shutil.which("rsvg-convert") is None:
        raise BuildError("rsvg-convert is not on PATH; install librsvg to build the rasters")
    args = ["rsvg-convert", "--width", str(width)]
    if height is not None:
        args += ["--height", str(height)]
    args += ["--output", str(png), str(svg)]
    subprocess.run(args, check=True)


def rasterize_text(
    svg_text: str, png: Path, width: int, height: int | None = None, scratch: Path | None = None
) -> None:
    scratch = scratch or png.parent
    scratch.mkdir(parents=True, exist_ok=True)
    source = scratch / (png.stem + ".source.svg")
    source.write_text(svg_text, encoding="utf-8")
    rsvg_convert(source, png, width, height)
    source.unlink()


@dataclass(frozen=True, slots=True)
class Placed:
    """A lockup placed in an image: the transform and the inner markup."""

    transform: str
    markup: str


def lockup_for(build: Build, touchpoint: Touchpoint | None, name: str | None) -> tuple[str, float, float]:
    """The property lockup (or the plain lockup for an empty name) in the on-dark ink."""
    ink = build.tokens.resolve("color.role.ink", "dark")
    divider = build.tokens.resolve("color.role.ink-label", "dark")
    if not name:
        parts, g = mark.lockup_parts(ink, build.word)
        return parts, g.width, g.height
    label: TextRun = build.label_font.run(name, space_em=mark.LABEL_SPACE_EM)
    lockup = mark.property_lockup_parts(ink, name, build.word, label, divider=divider)
    return lockup.markup, lockup.width, lockup.height


def place(
    markup: str, width: float, height: float, canvas_w: float, canvas_h: float, target_w: float, cy: float | None = None
) -> Placed:
    scale = min(target_w / width, (canvas_h * 0.3) / height)
    x = (canvas_w - width * scale) / 2
    y = (canvas_h - height * scale) / 2 if cy is None else cy - height * scale / 2
    return Placed(f"translate({x:.2f} {y:.2f}) scale({scale:.4f})", markup)


def og_svg(build: Build, touchpoint: Touchpoint) -> str:
    markup, width, height = lockup_for(build, touchpoint, touchpoint.property_name or None)
    placed = place(markup, width, height, 1200, 630, 760)
    host_name = touchpoint.host_name or ""
    run = build.label_font.run(host_name)
    size = 22.0
    host_svg = run.svg((1200 - run.width(size)) / 2, 560, size, build.tokens.resolve("color.role.ink-label", "dark"))
    return render_template(
        build,
        "og.svg",
        {
            "property": html.escape(touchpoint.property_name or "idfkit"),
            "lockup.transform": placed.transform,
            "lockup.svg": placed.markup,
            "host.svg": host_svg,
        },
    )


