def family_links_html(build: Build) -> str:
    links = "\n".join(f'  <a href="{link.href}">{html.escape(link.label)}</a>' for link in build.roster.family_links)
    return render_template(build, "family-links.html", {"links": links})


def ownership_html(build: Build) -> str:
    return f'<p class="idfkit-ownership">{html.escape(build.roster.ownership)}</p>\n'


def copy_fonts(build: Build, target: Path) -> None:
    for path in sorted((build.root / "fonts").iterdir()):
        if path.suffix == ".woff2" or path.name.startswith("LICENSE-"):
            copy(path, target / path.name)


def build_css(build: Build) -> None:
    out = build.out / "css"
    write(out / "tokens.css", tokens_css(build))
    write(out / "fonts.css", fonts_css(build, "--idfkit-font-text", "--idfkit-font-code"))
    write(out / "motion.css", motion_css(build))
    write(out / "forced-colors.css", forced_colors_css(build))
    write(out / "family-links.html", family_links_html(build))
    write(out / "ownership.html", ownership_html(build))
    copy_fonts(build, out / "fonts")


